#!/usr/bin/env python3
"""Populate the generated example plugin without linking back to its ancestor."""
from pathlib import Path
import shutil
root=Path(__file__).resolve().parent.parent
dest=root/'examples/TerrainDemo/Plugins/DynamicTerrain'
if dest.is_symlink():
    if dest.resolve()!=root:raise SystemExit(f'Refusing to replace an unrelated plugin link: {dest}')
    dest.unlink()
if dest.exists() and not (dest/'.xovium-generated-example').exists():
    raise SystemExit(f'Refusing to overwrite an unmarked example plugin: {dest}')
dest.mkdir(parents=True,exist_ok=True)
(dest/'.xovium-generated-example').write_text('Generated by scripts/prepare_example.py; edit the top-level plugin source.\n')
def ignored(directory,names):
    return [name for name in names if name in {'build','Binaries','Intermediate','Saved','DerivedDataCache','__pycache__'} or (Path(directory)/name).is_symlink()]
for name in ('Source','native','Content','tests','scripts'):
    shutil.copytree(root/name,dest/name,dirs_exist_ok=True,ignore=ignored)
for name in ('DynamicTerrain.uplugin','LICENSE','README.md','source-manifest.json','adapter-source-manifest.json'):
    shutil.copy2(root/name,dest/name)
(dest/'Binaries/Linux').mkdir(parents=True,exist_ok=True)
shutil.copy2(root/'Binaries/Linux/libxovium_dynamic_terrain.so',dest/'Binaries/Linux/libxovium_dynamic_terrain.so')
print(dest)
